def format_admin_contact_text(
    name: str,
    telegram: str,
    phone: str,
) -> str:
    lines = [
        "Контакт администратора студии «Ноготочки»:",
        f"Имя: {name}",
    ]
    if telegram:
        lines.append(f"Telegram: @{telegram}")
        lines.append(f"Написать: https://t.me/{telegram}")
    if phone:
        lines.append(f"Телефон: {phone}")
    return "\n".join(lines)


def format_service(service: Service) -> str:
    return (
        f"<b>{service.title}</b>\n"
        f"{service.description}\n\n"
        f"Цена: {service.price}\n"
        f"Длительность: {service.duration}"
    )


def format_services_list() -> str:
    lines = ["<b>Услуги и цены</b>\nВыберите услугу кнопкой ниже:\n"]
    for service in SERVICES:
        lines.append(f"• {service.title} — {service.price}")
    lines.append(
        "\nДля бронирования нужна полная предоплата; "
        "после оплаты мастер согласует дату и время."
    )
    return "\n".join(lines)


def format_faq() -> str:
    parts = ["<b>Частые вопросы</b>\n"]
    for question, answer in FAQ:
        parts.append(f"<b>{question}</b>\n{answer}\n")
    return "\n".join(parts)
